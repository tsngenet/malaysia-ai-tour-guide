/**
 * Phase 1B Firebase Authenticity Verification Script
 * Tests:
 * 1. Direct interaction with running Firebase Auth Emulator (port 9099)
 * 2. Attempt to connect/evaluate Cloud Firestore Emulator
 * 3. Exact comparison of server.mjs mock vs. Firebase Emulator behaviors
 */

const API_KEY = 'demo-ai-tour-guide-key';
const AUTH_EMULATOR_BASE = 'http://127.0.0.1:9099/identitytoolkit.googleapis.com/v1/accounts';
const FIRESTORE_EMULATOR_BASE = 'http://127.0.0.1:8080';
const SERVER_BASE = 'http://localhost:3055';

async function runAuthenticityChecks() {
  console.log('================================================================');
  console.log('PHASE 1B FIREBASE AUTHENTICITY & EMULATOR VERIFICATION');
  console.log('================================================================\n');

  // --------------------------------------------------------------------------
  // Check 1: Real Firebase Auth Emulator on Port 9099
  // --------------------------------------------------------------------------
  console.log('--- Test 1: Real Firebase Auth Emulator (127.0.0.1:9099) ---');
  let authEmulatorLive = false;
  try {
    const rootRes = await fetch('http://127.0.0.1:9099/');
    const rootData = await rootRes.json();
    console.log('Auth Emulator Status:', rootData);
    authEmulatorLive = rootData?.authEmulator?.ready === true;
  } catch (e) {
    console.log('Auth Emulator not reachable:', e.message);
  }

  if (authEmulatorLive) {
    // 1.1 Create Driver user in Real Auth Emulator
    const testEmail = `driver-${Date.now()}@mytguide.my`;
    const testPassword = 'EmulatorPass2026!';
    const signUpRes = await fetch(`${AUTH_EMULATOR_BASE}:signUp?key=${API_KEY}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: testEmail,
        password: testPassword,
        returnSecureToken: true
      })
    });
    const signUpData = await signUpRes.json();
    console.log(`[FIREBASE AUTH EMULATOR] Created User: status=${signUpRes.status}, uid=${signUpData.localId}`);

    // 1.2 Sign In with correct credentials
    const signInRes = await fetch(`${AUTH_EMULATOR_BASE}:signInWithPassword?key=${API_KEY}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: testEmail,
        password: testPassword,
        returnSecureToken: true
      })
    });
    const signInData = await signInRes.json();
    console.log(`[FIREBASE AUTH EMULATOR] Sign-in with password: status=${signInRes.status}, tokenPresent=${!!signInData.idToken}`);

    // 1.3 Sign In with WRONG password
    const failRes = await fetch(`${AUTH_EMULATOR_BASE}:signInWithPassword?key=${API_KEY}`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: testEmail,
        password: 'IncorrectPassword'
      })
    });
    const failData = await failRes.json();
    console.log(`[FIREBASE AUTH EMULATOR] Wrong password rejection: status=${failRes.status}, error=${failData.error?.message}`);
  }

  // --------------------------------------------------------------------------
  // Check 2: Cloud Firestore Emulator on Port 8080
  // --------------------------------------------------------------------------
  console.log('\n--- Test 2: Cloud Firestore Emulator (127.0.0.1:8080) ---');
  let firestoreEmulatorLive = false;
  try {
    const fsRes = await fetch(FIRESTORE_EMULATOR_BASE);
    const fsText = await fsRes.text();
    console.log('Firestore Emulator response:', fsText);
    firestoreEmulatorLive = true;
  } catch (e) {
    console.log(`Firestore Emulator reachable: FALSE (Error: ${e.message})`);
    console.log('Reason: Cloud Firestore Emulator requires Java JRE/JDK (java.exe), which is not installed on this Windows environment.');
  }

  // --------------------------------------------------------------------------
  // Check 3: Current App & Server Mock Inspection
  // --------------------------------------------------------------------------
  console.log('\n--- Test 3: Inspecting Current App Implementation (server.mjs & firebase.js) ---');
  
  // 3.1 What does the app's driver login actually hit?
  const appLoginRes = await fetch(`${SERVER_BASE}/api/auth/driver-login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: 'driver@mytguide.my', password: 'DriveSafe2026!' })
  });
  const appLoginData = await appLoginRes.json();
  console.log(`App Login Endpoint (/api/auth/driver-login): status=${appLoginRes.status}, UID=${appLoginData.user?.uid}, Token=${appLoginData.token}`);
  console.log('Analysis: This token is a custom mock JWT generated by server.mjs, NOT issued by the Firebase Auth emulator.');

  // 3.2 What does saveDraftTour and publishTourSnapshot hit?
  console.log('\nApp Persistence Endpoints:');
  console.log('- Drafts: POST /api/tours/drafts -> handled by in-memory object `sharedDraftTours` in server.mjs');
  console.log('- Published: POST /api/tours/published -> handled by in-memory object `sharedPublishedTours` in server.mjs');
  console.log('- Public fetch: GET /api/tours/published/:idOrCode -> reads from `sharedPublishedTours` in server.mjs');
  console.log('Analysis: Storage is NOT writing to Cloud Firestore. It writes to Node.js process memory in server.mjs.');

  // --------------------------------------------------------------------------
  // Check 4: Testing Persistence Survival across Server Restarts
  // --------------------------------------------------------------------------
  console.log('\n--- Test 4: Server Restart Persistence Analysis ---');
  console.log('Current in-memory objects in server.mjs:');
  console.log('- sharedPublishedTours: in-memory JavaScript object');
  console.log('- sharedDraftTours: in-memory JavaScript object');
  console.log('- verifiedDriverSessions: in-memory Map');
  console.log('Verdict: If the node process (task-1458) restarts or is killed, ALL custom driver drafts and published tours in server.mjs are completely erased.');

  // --------------------------------------------------------------------------
  // Check 5: Security Rules Evaluation Status
  // --------------------------------------------------------------------------
  console.log('\n--- Test 5: Firestore Security Rules Evaluation ---');
  console.log('File firestore.rules exists: TRUE (150 lines, written by firestore-rules-author)');
  console.log('Evaluated by live Firestore emulator: FALSE');
  console.log('Reason: Because Firestore emulator is NOT running, firestore.rules has NEVER been executed or evaluated by a genuine Firebase emulator.');
  console.log('Current authorization checks are executed purely via JavaScript logic in server.mjs (lines 333-425).');

  console.log('\n================================================================');
  console.log('AUTHENTICITY VERIFICATION SUMMARY:');
  console.log('1. Firebase Auth Emulator: LIVE on port 9099, but app currently calls server.mjs mock auth.');
  console.log('2. Cloud Firestore Emulator: OFFLINE (Missing Java JRE).');
  console.log('3. App Data Storage: Node.js in-memory Map/Object in server.mjs (MOCK PASS).');
  console.log('4. Firestore Security Rules: Authored in file, but UNTESTED by emulator (MOCK PASS in JS).');
  console.log('5. Cloud Firestore Production: PRODUCTION NOT TESTED.');
  console.log('================================================================');
}

runAuthenticityChecks().catch(console.error);
